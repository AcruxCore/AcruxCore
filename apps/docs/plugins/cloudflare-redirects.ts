import fs from 'node:fs/promises';
import nodePath from 'node:path';
import type {LoadContext, Plugin} from '@docusaurus/types';
import type {RedirectEntry} from '../redirects';

/**
 * Options passed from `docusaurus.config.ts`.
 */
export interface CloudflareRedirectsOptions {
  /** The shared list from `redirects.ts`. */
  redirects: readonly RedirectEntry[];
}

/**
 * Renders the Cloudflare Pages `_redirects` file.
 *
 * Each entry gets two lines, with and without a trailing slash, because Pages
 * matches the path literally and an old link may carry either form.
 */
function renderRedirects(redirects: readonly RedirectEntry[]): string {
  const lines = [
    '# Generated by plugins/cloudflare-redirects.ts from redirects.ts. Do not edit.',
  ];
  for (const {from, to} of redirects) {
    lines.push(`${from} ${to} 301`, `${from}/ ${to} 301`);
  }
  return `${lines.join('\n')}\n`;
}

/**
 * Writes `_redirects` into the build root so Cloudflare Pages answers each
 * retired URL with a real HTTP 301.
 *
 * `@docusaurus/plugin-client-redirects` only emits meta-refresh HTML pages.
 * Search engines usually treat an instant meta refresh as permanent, but more
 * slowly than a 301, and link checkers and social-preview bots do not follow it
 * at all. Pages reads `_redirects` before it serves a static file, so the 301
 * wins and the HTML page stays as a fallback for other hosts.
 *
 * The file is written into the build output rather than `static/` so it is
 * generated from the same list as the client redirects and cannot drift. That
 * also means it needs no checks of its own: the client-redirects plugin fails
 * the build when an entry points at a page that does not exist.
 *
 * @param _context - Docusaurus load context (unused).
 * @param options - The shared redirect list.
 * @returns The plugin, whose only hook is `postBuild`.
 */
export default function cloudflareRedirectsPlugin(
  _context: LoadContext,
  options: CloudflareRedirectsOptions,
): Plugin<void> {
  return {
    name: 'acruxcore-cloudflare-redirects',

    async postBuild({outDir}) {
      await fs.writeFile(
        nodePath.join(outDir, '_redirects'),
        renderRedirects(options.redirects),
        'utf8',
      );
      console.log(`[_redirects] Wrote ${options.redirects.length} redirects.`);
    },
  };
}
