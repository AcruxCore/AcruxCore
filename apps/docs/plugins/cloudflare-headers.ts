import fs from 'node:fs/promises';
import nodePath from 'node:path';
import type {LoadContext, Plugin} from '@docusaurus/types';

/** One `_headers` rule: a path pattern and the headers Pages adds to it. */
export interface HeaderRule {
  /** Path or splat pattern, e.g. `/assets/*`. */
  path: string;
  /** Header name to value. */
  headers: Readonly<Record<string, string>>;
}

/** Options passed from a Docusaurus config. */
export interface CloudflareHeadersOptions {
  /** Rules in the order they are written. */
  rules: readonly HeaderRule[];
}

/**
 * Everything under `assets/` is named by content hash (`main.54b4ee74.js`), so
 * a changed file always gets a new URL and the old one can be cached for good.
 * Without a rule, Pages sends `max-age=0, must-revalidate` and Cloudflare's
 * browser TTL raised it only to 4 hours.
 */
const IMMUTABLE = {'Cache-Control': 'public, max-age=31536000, immutable'};

/**
 * llms.txt is Markdown, and the Link header that points agents at it says
 * `type="text/markdown"`; Pages would otherwise send `text/plain`.
 */
const MARKDOWN = {'Content-Type': 'text/markdown; charset=utf-8'};

/**
 * `_headers` rules for docs.acruxcore.com, which Pages serves directly — so the
 * security headers are set here. The blog gets its own from the marketing
 * site's nginx instead (see {@link blogHeaderRules}).
 *
 * The Link header is scoped to `/` only: a Link header set by `_headers`
 * replaces the preload hints Pages generates from each page's HTML, and the
 * home page is where discovery tools look.
 *
 * @returns The docs site's rules.
 */
export function docsHeaderRules(): HeaderRule[] {
  return [
    {
      path: '/*',
      headers: {
        'Strict-Transport-Security': 'max-age=31536000; includeSubDomains',
        'X-Frame-Options': 'DENY',
      },
    },
    {path: '/assets/*', headers: IMMUTABLE},
    {path: '/llms.txt', headers: MARKDOWN},
    {
      path: '/',
      headers: {
        Link: '<https://acruxcore.com/.well-known/api-catalog>; rel="api-catalog", </api-reference>; rel="service-doc", </llms.txt>; rel="describedby"; type="text/markdown"',
      },
    },
  ];
}

/**
 * `_headers` rules for the blog's Pages project. Paths carry `/blog` because
 * CI nests the build under `blog/` so the path on Pages equals the public path.
 *
 * @returns The blog's rules.
 */
export function blogHeaderRules(): HeaderRule[] {
  return [
    {path: '/blog/assets/*', headers: IMMUTABLE},
    {path: '/blog/llms.txt', headers: MARKDOWN},
  ];
}

/**
 * Renders a Cloudflare Pages `_headers` file.
 *
 * @param rules - Rules in order; each becomes a path line followed by its
 *   indented `Name: value` lines.
 * @returns The file contents, newline-terminated.
 */
export function renderHeaders(rules: readonly HeaderRule[]): string {
  const lines = ['# Generated by plugins/cloudflare-headers.ts. Do not edit.'];
  for (const rule of rules) {
    lines.push(rule.path);
    for (const [name, value] of Object.entries(rule.headers)) {
      lines.push(`  ${name}: ${value}`);
    }
  }
  return `${lines.join('\n')}\n`;
}

/**
 * Writes `_headers` into the build root, from rules in the site's config.
 *
 * Generated rather than kept in `static/`, because `static/` is shared by the
 * docs and blog builds and the two hosts need different rules.
 *
 * @param _context - Docusaurus load context (unused).
 * @param options - The rules to write.
 * @returns The plugin, whose only hook is `postBuild`.
 */
export default function cloudflareHeadersPlugin(
  _context: LoadContext,
  options: CloudflareHeadersOptions,
): Plugin<void> {
  return {
    name: 'acruxcore-cloudflare-headers',

    async postBuild({outDir}) {
      await fs.writeFile(nodePath.join(outDir, '_headers'), renderHeaders(options.rules), 'utf8');
      console.log(`[_headers] Wrote ${options.rules.length} rules.`);
    },
  };
}
