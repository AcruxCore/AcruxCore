#!/bin/sh
# Writes the /blog/ reverse-proxy block when BLOG_UPSTREAM is set, and nothing
# otherwise. The official nginx image runs every executable *.sh in
# /docker-entrypoint.d/ before nginx starts; nginx.conf includes whatever this
# leaves in /etc/nginx/acruxcore/.
#
# Why it is optional: this is the image every self-hosted install pulls, and only
# acruxcore.com serves the AcruxCore blog (a second Cloudflare Pages project, see
# apps/docs/DEPLOY.md). Unset, /blog behaves exactly as before — the SPA shell,
# served noindex.
#
# The value is checked against the characters an origin can contain before it
# goes into nginx config. A value that fails is dropped with a warning, so a
# typo in .env turns the blog proxy off instead of stopping nginx.
set -eu

dir=/etc/nginx/acruxcore
mkdir -p "$dir"
rm -f "$dir"/blog-*.conf

upstream="${BLOG_UPSTREAM:-}"
[ -n "$upstream" ] || exit 0
if ! printf '%s' "$upstream" | grep -Eq '^https?://[A-Za-z0-9.-]+(:[0-9]+)?$'; then
  echo "blog-proxy: BLOG_UPSTREAM is not a bare http(s) origin like https://acruxcore-blog.pages.dev; /blog is not proxied" >&2
  exit 0
fi

cat >"$dir/blog-proxy.conf" <<CONF
# Generated by /docker-entrypoint.d/41-blog-proxy.sh from BLOG_UPSTREAM.

# The blog index lives at /blog/ (a Docusaurus baseUrl ends in a slash, and
# Pages serves a folder index there). absolute_redirect off keeps this relative.
location = /blog {
    return 301 /blog/\$is_args\$args;
}

# ^~ so neither the trailing-slash regex nor the noindex SPA fallback ever sees
# a blog path. The upstream serves the same /blog/... paths (the deploy nests the
# build under blog/), so the URI passes through unchanged.
location ^~ /blog/ {
    # A variable in proxy_pass makes nginx resolve the host per request (cached
    # for valid=), so a change in the Pages IPs needs no restart. 127.0.0.11 is
    # Docker's embedded DNS, present on every compose network.
    resolver 127.0.0.11 valid=300s ipv6=off;
    set \$blog_upstream $upstream;
    proxy_pass \$blog_upstream;
    proxy_ssl_server_name on;
    proxy_http_version 1.1;
    # A Location pointing at the upstream host (pages.dev) becomes a path on
    # this host instead of sending the visitor to pages.dev.
    proxy_redirect $upstream/ /;
    # An upstream 404 stays a 404, never the marketing shell with a 200.
    proxy_intercept_errors off;
}
CONF
echo "blog-proxy: /blog/ -> $upstream"
